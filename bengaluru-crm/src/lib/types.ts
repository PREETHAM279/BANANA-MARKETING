export type Phone = { number: string; label: string; source: string; type: "mobile" | "landline" };
export type EmailItem = { email: string; label: string; source: string };
export type Person = { name: string; role: string; type: "owner" | "manager" | "other"; source: string };
export type Source = { label: string; url: string };
export type Objection = { q: string; a: string };

export type ActivityItem = {
  id: string;
  businessId: string;
  businessName?: string;
  type: string;
  outcome: string;
  summary: string;
  details: string;
  meta: Record<string, unknown>;
  occurredAt: string;
  createdAt: string;
};

export type NoteItem = { id: string; kind: string; content: string; createdAt: string; updatedAt: string };
export type PhotoItem = { id: string; fileName: string; caption: string; source: string; createdAt: string; url: string };
export type RecordingItem = { id: string; fileName: string; mimeType: string; durationSec: number; note: string; createdAt: string; url: string };

export type SiteData = {
  url: string;
  finalUrl?: string;
  title?: string;
  description?: string;
  image?: string | null;
  emails: string[];
  phones: string[];
  socials: Record<string, string>;
  fetchedAt: string;
  error?: string;
};

export type GoogleData = {
  placeId: string;
  name?: string;
  address?: string;
  rating?: number | null;
  userRatingCount?: number | null;
  mapsUri?: string | null;
  phone?: string | null;
  website?: string | null;
  businessStatus?: string | null;
  photos: { name: string; attributions: { displayName?: string; uri?: string }[] }[];
  fetchedAt: string;
};

